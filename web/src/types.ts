import type { LyricLine } from "./engine/lyrics";

export interface PausePoint {
  at: number;
  question: string;
  options: string[];
  correct: number;
  explain: string;
}

export interface Topic {
  id: string;
  field: string;
  title: string;
  bpm: number;
  audio: string;
  duration?: number;
  beat_offset?: number;
  time_offset?: number;
  time_scale?: number;
  lyrics: LyricLine[];
  scenes: {
    template: string;
    start: number;
    end: number;
    params: Record<string, unknown>;
  }[];
  pauses: PausePoint[];
}

export interface GeneratedSong extends Omit<Topic, "audio" | "field" | "id"> {
  topic_id: string;
  model_used: string;
  repairs_used: number;
}

export interface CatalogEntry {
  id: string;
  title: string;
  ready: boolean;
  status?: "ready" | "audio_pending";
  file?: string;
  subtopics?: string[];
}

export interface Catalog {
  topics: CatalogEntry[];
}

export interface QuizQuestion {
  question: string;
  options: string[];
  correct_index: number;
  explanation: string;
  id?: string;
  source?: "AI-generated" | "generated by code" | "curated";
  scene?: "sum_node" | "gate_fire" | "sigmoid_curve" | "weight_update";
  seek?: number;
}

export interface QuizResponse {
  topic_id: string;
  questions: QuizQuestion[];
  model_used: string;
  repairs_used: number;
}
