import type { QuizQuestion } from "../types";

const INPUTS = [-3, -2, -1, -0.5, 0.5, 1, 2, 3] as const;
const FUNCTIONS = [
  "step",
  "sigmoid",
  "tanh",
  "ReLU",
  "Leaky ReLU (alpha = 0.1)",
  "PReLU (alpha = 0.25)",
  "ELU (alpha = 1)",
  "swish",
] as const;
const SEEKS: Record<ActivationFunction, number> = {
  step: 0,
  sigmoid: 19.88,
  tanh: 28.68,
  ReLU: 56.84,
  "Leaky ReLU (alpha = 0.1)": 66.94,
  "PReLU (alpha = 0.25)": 71.66,
  "ELU (alpha = 1)": 94.17,
  swish: 106.3,
};
const RANGE_QUESTIONS = [
  "Which function can output a negative value but never go below -1 or above 1?",
  "Which function can output below 0 while staying between -1 and 1 for every z?",
  "Which function's output can be negative, but never falls below -1 or rises above 1?",
  "Which function can be less than 0 without ever going below -1 or above 1?",
] as const;

export type ActivationFunction = typeof FUNCTIONS[number];
type Calculation =
  | { kind: "output"; activation: ActivationFunction; z: number; value: number }
  | { kind: "range"; activation: "tanh" };

export interface ActivationQuestion extends QuizQuestion {
  id: string;
  expectedAnswer: string;
  calculation: Calculation;
}

function pick<T>(values: readonly T[], random: () => number): T {
  const value = values[Math.min(values.length - 1, Math.floor(random() * values.length))];
  if (value === undefined) throw new Error("Cannot choose from an empty list");
  return value;
}

function valueAt(activation: ActivationFunction, z: number): number {
  switch (activation) {
    case "step":
      return z >= 0 ? 1 : 0;
    case "sigmoid":
      return 1 / (1 + Math.exp(-z));
    case "tanh":
      return Math.tanh(z);
    case "ReLU":
      return Math.max(0, z);
    case "Leaky ReLU (alpha = 0.1)":
      return z >= 0 ? z : 0.1 * z;
    case "PReLU (alpha = 0.25)":
      return z >= 0 ? z : 0.25 * z;
    case "ELU (alpha = 1)":
      return z >= 0 ? z : Math.exp(z) - 1;
    case "swish":
      return z / (1 + Math.exp(-z));
  }
}

function formatted(value: number): string {
  const rounded = Number(value.toFixed(2));
  return (Object.is(rounded, -0) ? 0 : rounded).toFixed(2);
}

function shuffled<T>(values: T[], random: () => number): T[] {
  for (let index = values.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [values[index], values[swap]] = [values[swap]!, values[index]!];
  }
  return values;
}

function outputQuestion(random: () => number): ActivationQuestion {
  for (let attempt = 0; attempt < 1000; attempt += 1) {
    const z = pick(INPUTS, random);
    const activation = pick(FUNCTIONS, random);
    const value = valueAt(activation, z);
    const expectedAnswer = formatted(value);
    const signError = formatted(-value);
    if (signError === expectedAnswer) continue;

    const distractors = FUNCTIONS
      .filter((other) => other !== activation)
      .map((other) => formatted(valueAt(other, z)));
    const options = [...new Set([expectedAnswer, ...distractors, signError])];
    if (options.length < 3) continue;
    return {
      id: `activation:output:${activation}:${z}`,
      source: "generated by code",
      question: `z = ${z}. What does ${activation} output (2 decimals)?`,
      options: shuffled(options, random),
      correct_index: options.indexOf(expectedAnswer),
      explanation: `${activation}(${z}) = ${expectedAnswer}.`,
      seek: SEEKS[activation],
      expectedAnswer,
      calculation: { kind: "output", activation, z, value },
    };
  }
  throw new Error("Could not generate an activation output question");
}

function functionQuestion(random: () => number): ActivationQuestion {
  for (let attempt = 0; attempt < 1000; attempt += 1) {
    const z = pick(INPUTS, random);
    const values = new Map(FUNCTIONS.map((activation) => [
      activation,
      formatted(valueAt(activation, z)),
    ]));
    const uniqueFunctions = FUNCTIONS.filter((activation) =>
      FUNCTIONS.filter((other) => values.get(other) === values.get(activation)).length === 1);
    if (uniqueFunctions.length === 0) continue;

    const activation = pick(uniqueFunctions, random);
    const expectedAnswer = activation;
    const output = values.get(activation);
    if (output === undefined) throw new Error("Activation output was not calculated");
    const options = shuffled([
      ...shuffled(FUNCTIONS.filter((item) => item !== activation), random).slice(0, 3),
      activation,
    ], random);
    return {
      id: `activation:function:${activation}:${z}`,
      source: "generated by code",
      question: `Which function gives ${output} at z = ${z}?`,
      options,
      correct_index: options.indexOf(expectedAnswer),
      explanation: `${activation}(${z}) = ${output}.`,
      seek: SEEKS[activation],
      expectedAnswer,
      calculation: { kind: "output", activation, z, value: valueAt(activation, z) },
    };
  }
  throw new Error("Could not generate an activation function question");
}

function rangeQuestion(random: () => number): ActivationQuestion {
  const question = pick(RANGE_QUESTIONS, random);
  const options = shuffled([
    ...shuffled(FUNCTIONS.filter((item) => item !== "tanh"), random).slice(0, 3),
    "tanh",
  ], random);
  return {
    id: `activation:range:${question}`,
    source: "generated by code",
    question,
    options,
    correct_index: options.indexOf("tanh"),
    explanation: "tanh outputs values strictly between -1 and 1.",
    seek: SEEKS.tanh,
    expectedAnswer: "tanh",
    calculation: { kind: "range", activation: "tanh" },
  };
}

export function generateActivationQuestions(
  random: () => number = Math.random,
  count = 3,
  excludedIds: readonly string[] = [],
): ActivationQuestion[] {
  if (!Number.isInteger(count) || count < 1) throw new Error("Question count must be a positive integer");
  const excluded = new Set(excludedIds);
  const questions: ActivationQuestion[] = [];
  let rangeAdded = false;
  let attempts = 0;
  while (questions.length < count) {
    if (attempts > count * 1000) throw new Error("Could not generate enough unused activation questions");
    const question = !rangeAdded && ((count >= 3 && questions.length === count - 1) || random() < 0.2)
      ? rangeQuestion(random)
      : random() < 0.5
        ? outputQuestion(random)
        : functionQuestion(random);
    attempts += 1;
    if (excluded.has(question.id) || questions.some((item) => item.id === question.id)) continue;
    questions.push(question);
    if (question.calculation.kind === "range") rangeAdded = true;
  }
  if (count >= 3 && !rangeAdded) {
    throw new Error("Activation quiz is missing its range question");
  }
  return questions;
}

export function hasCorrectActivationArithmetic(question: ActivationQuestion): boolean {
  if (question.calculation.kind === "range") {
    return question.expectedAnswer === "tanh"
      && question.options[question.correct_index] === "tanh";
  }
  const expected = question.calculation.activation;
  const correctValue = valueAt(expected, question.calculation.z);
  const correctAnswer = question.question.startsWith("Which function gives ")
    ? expected
    : formatted(correctValue);
  return question.expectedAnswer === correctAnswer
    && question.options[question.correct_index] === correctAnswer
    && question.calculation.value === correctValue;
}
