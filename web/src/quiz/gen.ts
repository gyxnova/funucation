import type { QuizQuestion } from "../types";

type Calculation =
  | { kind: "z"; inputs: number[]; weights: number[]; bias: number }
  | { kind: "fires"; z: number; inputs: number[]; weights: number[]; bias: number }
  | { kind: "sigmoid"; z: number; inputs: number[]; weights: number[]; bias: number }
  | { kind: "update"; index: number; weight: number; input: number; target: number; output: number; rate: number };

export interface GeneratedQuestion extends QuizQuestion {
  id: string;
  expectedAnswer: string;
  calculation: Calculation;
}

const WEIGHTS = [-2, -1, -0.5, 0.5, 1, 2];
const BIASES = [-3, -2, -1, 0, 1];
const OTHER_TYPES = ["z", "fires", "sigmoid"] as const;

function pick<T>(values: readonly T[], random: () => number): T {
  const index = Math.min(values.length - 1, Math.floor(random() * values.length));
  const value = values[index];
  if (value === undefined) throw new Error("Cannot choose from an empty list");
  return value;
}

function formatNumber(value: number): string {
  const rounded = Math.round(value * 100) / 100;
  return Object.is(rounded, -0) ? "0" : String(rounded);
}

function sigmoid(value: number): number {
  return 1 / (1 + Math.exp(-value));
}

function shuffle<T>(values: T[], random: () => number): T[] {
  for (let index = values.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [values[index], values[swap]] = [values[swap]!, values[index]!];
  }
  return values;
}

function distinctDistractors(
  correct: string,
  candidates: string[],
  formatter: (value: number) => string,
): string[] {
  const distinct = [...new Set(candidates.filter((candidate) => candidate !== correct))];
  for (let offset = 1; distinct.length < 3 && offset <= 20; offset += 1) {
    const alternative = formatter(Number(correct) + offset * 0.5);
    if (alternative !== correct && !distinct.includes(alternative)) distinct.push(alternative);
  }
  if (distinct.length < 3) throw new Error("Could not make three distinct distractors");
  return distinct.slice(0, 3);
}

function numericQuestion(
  question: string,
  correctValue: number,
  candidates: number[],
  explanation: string,
  calculation: Calculation,
  scene: GeneratedQuestion["scene"],
  random: () => number,
  formatter: (value: number) => string = formatNumber,
): GeneratedQuestion {
  const expectedAnswer = formatter(correctValue);
  const options = shuffle(
    [expectedAnswer, ...distinctDistractors(expectedAnswer, candidates.map(formatter), formatter)],
    random,
  );
  return {
    id: `${calculation.kind}:${JSON.stringify(calculation)}`,
    source: "generated by code",
    scene,
    question,
    options,
    correct_index: options.indexOf(expectedAnswer),
    explanation,
    expectedAnswer,
    calculation,
  };
}

function makeGeneratedQuestion(
  type: typeof OTHER_TYPES[number] | "update",
  random: () => number,
): GeneratedQuestion {
  let inputs: number[] = [0, 0, 0].map(() => Math.floor(random() * 2));
  if (inputs.every((input) => input === 0)) {
    const activeIndex = Math.floor(random() * 3);
    inputs = inputs.map((input, index) => index === activeIndex ? 1 : input);
  }
  const weights = inputs.map(() => pick(WEIGHTS, random));
  const bias = pick(BIASES, random);
  const dot = inputs.reduce((sum, input, index) => sum + input * (weights[index] ?? 0), 0);
  const z = dot + bias;
  const inputText = `(${inputs.join(", ")})`;
  const weightText = `(${weights.map(formatNumber).join(", ")})`;

  if (type === "update") {
    const activeIndices = inputs.flatMap((input, index) => input === 1 ? [index] : []);
    const index = pick(activeIndices, random);
    const currentWeight = weights[index] ?? 0;
    const input = inputs[index] ?? 0;
    const target = 0;
    const output = 1;
    const rate = 1;
    const correct = currentWeight + rate * (target - output) * input;
    const calculation: Calculation = {
      kind: "update",
      index,
      weight: currentWeight,
      input,
      target,
      output,
      rate,
    };
    return numericQuestion(
      `With target=${target}, output=${output}, learning rate=${rate}, x${index + 1}=${input}, and current w${index + 1}=${formatNumber(currentWeight)}, what is the updated w${index + 1} using w_new = w + rate*(target-output)*x?`,
      correct,
      [
        currentWeight + rate * (output - target) * input,
        currentWeight,
        currentWeight + (target - output),
        currentWeight + 2 * rate * (target - output) * input,
      ],
      `w_new = ${formatNumber(currentWeight)} + ${rate}*(${target}-${output})*${input} = ${formatNumber(correct)}.`,
      calculation,
      "weight_update",
      random,
    );
  }

  if (type === "z") {
    const correct = z;
    const calculation: Calculation = { kind: "z", inputs, weights, bias };
    return numericQuestion(
      `For x=${inputText}, w=${weightText}, and bias b=${formatNumber(bias)}, what is z = w.x + b?`,
      correct,
      [
        dot,
        dot - bias,
        weights.reduce((sum, weight) => sum + weight, bias),
        ...inputs.map((input, index) => dot - input * (weights[index] ?? 0) + bias),
      ],
      `z = ${weights.map((weight, index) => `${formatNumber(weight)}*${inputs[index]}`).join(" + ")} + (${formatNumber(bias)}) = ${formatNumber(correct)}.`,
      calculation,
      "sum_node",
      random,
    );
  }

  if (type === "fires") {
    const correct = z >= 0 ? "Yes" : "No";
    const expectedAnswer = correct === "Yes" ? "Yes — fires" : "No — does not fire";
    const options = shuffle(["Yes — fires", "No — does not fire"], random);
    const calculation: Calculation = { kind: "fires", z, inputs, weights, bias };
    return {
      id: `fires:${JSON.stringify(calculation)}`,
      source: "generated by code",
      scene: "gate_fire",
      question: `For x=${inputText}, w=${weightText}, and bias b=${formatNumber(bias)}, z=${formatNumber(z)}. Does it fire under the rule z >= 0?`,
      options,
      correct_index: options.indexOf(expectedAnswer),
      explanation: `z=${formatNumber(z)}, so the rule z >= 0 means ${correct === "Yes" ? "it fires" : "it does not fire"}.`,
      expectedAnswer,
      calculation,
    };
  }

  const correct = sigmoid(z);
  const mistakenValues = [
    sigmoid(dot),
    sigmoid(dot - bias),
    sigmoid(-z),
    ...inputs.map((input, index) => sigmoid(dot - input * (weights[index] ?? 0) + bias)),
    sigmoid(z + 1),
    sigmoid(z - 1),
  ];
  const calculation: Calculation = { kind: "sigmoid", z, inputs, weights, bias };
  return numericQuestion(
    `For x=${inputText}, w=${weightText}, and bias b=${formatNumber(bias)}, z=${formatNumber(z)}. What is sigmoid(z)=1/(1+e^-z), to 2 decimals?`,
    correct,
    mistakenValues,
    `sigmoid(${formatNumber(z)}) = ${correct.toFixed(2)}.`,
    calculation,
    "sigmoid_curve",
    random,
    (value) => value.toFixed(2),
  );
}

export function generateQuestions(
  random: () => number = Math.random,
  count = 3,
  excludedIds: readonly string[] = [],
): GeneratedQuestion[] {
  if (!Number.isInteger(count) || count < 1) throw new Error("Question count must be a positive integer");
  const excluded = new Set(excludedIds);
  const questions: GeneratedQuestion[] = [];
  const categories: (typeof OTHER_TYPES[number] | "update")[] = count === 3
    ? ["update", ...shuffle([...OTHER_TYPES], random).slice(0, 2)]
    : [];
  let attempts = 0;

  const fallbackTypes: readonly (typeof OTHER_TYPES[number] | "update")[] = [...OTHER_TYPES, "update"];
  while (questions.length < count) {
    if (attempts > count * 1000) throw new Error("Could not generate enough unused quiz questions");
    const fallbackType = pick(fallbackTypes, random);
    const type: typeof OTHER_TYPES[number] | "update" = categories[questions.length] ?? fallbackType;
    const question = makeGeneratedQuestion(type, random);
    attempts += 1;
    if (excluded.has(question.id) || questions.some((item) => item.id === question.id)) continue;
    questions.push(question);
  }
  return questions;
}

export function hasCorrectArithmetic(question: GeneratedQuestion): boolean {
  const { calculation, expectedAnswer } = question;
  let expected: string;
  switch (calculation.kind) {
    case "z":
      expected = formatNumber(calculation.inputs.reduce(
        (sum, input, index) => sum + input * (calculation.weights[index] ?? 0),
        calculation.bias,
      ));
      break;
    case "fires":
      expected = calculation.z >= 0 ? "Yes" : "No";
      break;
    case "sigmoid":
      expected = sigmoid(calculation.z).toFixed(2);
      break;
    case "update":
      expected = formatNumber(
        calculation.weight
          + calculation.rate * (calculation.target - calculation.output) * calculation.input,
      );
      break;
  }
  const answerMatches = calculation.kind === "fires"
    ? expectedAnswer.startsWith(`${expected} —`)
    : expected === expectedAnswer;
  return answerMatches
    && question.options[question.correct_index] === expectedAnswer;
}
